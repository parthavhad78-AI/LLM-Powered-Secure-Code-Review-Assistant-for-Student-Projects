export function recommendTopicsForCategories(categories: string[]): LearningTopic[] {
  const catSet = new Set(categories.map((c) => c.toLowerCase()));
  const matched = LEARNING_TOPICS.filter((topic) =>
    topic.relatedCategories.some((rc) => catSet.has(rc.toLowerCase()))
  );
  return matched.length > 0 ? matched : LEARNING_TOPICS.slice(0, 3);
}
